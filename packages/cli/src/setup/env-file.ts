import { readFile } from "node:fs/promises";

/** Keys written to the installation `.env` and checked for host-shell conflicts. */
export const INSTALL_ENV_KEYS = [
  "COMPOSE_PROJECT_NAME",
  "OSVA_IMAGE",
  "POSTGRES_PASSWORD",
  "OSVA_AUTH_SECRET",
  "OSVA_PUBLISH_WEB_PORT",
  "OSVA_PUBLISH_MCP_PORT",
  "OSVA_PUBLISH_CONSOLE_PORT",
  "OSVA_AUTH_BASE_URL",
  "OSVA_AUTH_TRUSTED_ORIGINS",
  "OSVA_VALKEY_URL",
] as const;

export type InstallEnvKey = (typeof INSTALL_ENV_KEYS)[number];

export type InstallEnvValues = Record<InstallEnvKey, string>;

export interface EnvConflict {
  readonly key: InstallEnvKey;
  readonly shellValue: string;
  readonly fileValue: string;
}

export function parseDotEnv(contents: string): Map<string, string> {
  const values = new Map<string, string>();
  for (const line of contents.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (trimmed.length === 0 || trimmed.startsWith("#")) {
      continue;
    }
    const withoutExport = trimmed.startsWith("export ")
      ? trimmed.slice("export ".length).trim()
      : trimmed;
    const eq = withoutExport.indexOf("=");
    if (eq <= 0) {
      continue;
    }
    const key = withoutExport.slice(0, eq).trim();
    let value = withoutExport.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values.set(key, value);
  }
  return values;
}

export async function readInstallEnvFile(
  envPath: string,
): Promise<Map<string, string> | undefined> {
  try {
    const contents = await readFile(envPath, "utf8");
    return parseDotEnv(contents);
  } catch (error) {
    if (
      error instanceof Error &&
      "code" in error &&
      (error as NodeJS.ErrnoException).code === "ENOENT"
    ) {
      return undefined;
    }
    throw error;
  }
}

export function detectShellEnvConflicts(
  fileValues: InstallEnvValues,
  shellEnv: NodeJS.ProcessEnv,
): readonly EnvConflict[] {
  const conflicts: EnvConflict[] = [];
  for (const key of INSTALL_ENV_KEYS) {
    const shellRaw =
      key === "COMPOSE_PROJECT_NAME"
        ? shellEnv.COMPOSE_PROJECT_NAME?.trim()
        : shellEnv[key]?.trim();
    if (shellRaw === undefined || shellRaw.length === 0) {
      continue;
    }
    const fileValue = fileValues[key];
    if (shellRaw !== fileValue) {
      conflicts.push({ key, shellValue: shellRaw, fileValue });
    }
  }
  return conflicts;
}

export function renderInstallEnvFile(values: InstallEnvValues): string {
  const lines = [
    "# Generated by `osva setup`. Do not commit this file.",
    "# Host shell exports override these values during `docker compose` interpolation.",
    "",
    `COMPOSE_PROJECT_NAME=${values.COMPOSE_PROJECT_NAME}`,
    "",
    `OSVA_IMAGE=${values.OSVA_IMAGE}`,
    `POSTGRES_PASSWORD=${values.POSTGRES_PASSWORD}`,
    "",
    "OSVA_VALKEY_URL=redis://valkey:6379",
    "",
    `OSVA_PUBLISH_WEB_PORT=${values.OSVA_PUBLISH_WEB_PORT}`,
    `OSVA_PUBLISH_MCP_PORT=${values.OSVA_PUBLISH_MCP_PORT}`,
    `OSVA_PUBLISH_CONSOLE_PORT=${values.OSVA_PUBLISH_CONSOLE_PORT}`,
    "",
    `OSVA_AUTH_SECRET=${values.OSVA_AUTH_SECRET}`,
    `OSVA_AUTH_BASE_URL=${values.OSVA_AUTH_BASE_URL}`,
    `OSVA_AUTH_TRUSTED_ORIGINS=${values.OSVA_AUTH_TRUSTED_ORIGINS}`,
    "",
    "OSVA_KNOWLEDGE_EMBEDDING_PROVIDER=DETERMINISTIC",
    "OSVA_KNOWLEDGE_EMBEDDING_MODEL=deterministic-v1",
    "OSVA_KNOWLEDGE_EMBEDDING_DIMENSIONS=384",
    "",
  ];
  return `${lines.join("\n")}\n`;
}

export function buildInstallEnvValues(input: {
  readonly imageRef: string;
  readonly composeProjectName: string;
  readonly webPort: number;
  readonly mcpPort: number;
  readonly consolePort: number;
  readonly existing?: Map<string, string>;
  readonly generateSecret: () => string;
}): InstallEnvValues {
  const webOrigin = `http://127.0.0.1:${String(input.webPort)}`;
  const consoleOrigin = `http://127.0.0.1:${String(input.consolePort)}`;
  const existing = input.existing;
  const postgresPassword =
    existing?.get("POSTGRES_PASSWORD")?.trim() || input.generateSecret();
  const authSecret =
    existing?.get("OSVA_AUTH_SECRET")?.trim() || input.generateSecret();
  const imageRef = existing?.get("OSVA_IMAGE")?.trim() || input.imageRef;
  assertRequiredSecret("POSTGRES_PASSWORD", postgresPassword);
  assertRequiredSecret("OSVA_AUTH_SECRET", authSecret);
  const composeProjectName =
    existing?.get("COMPOSE_PROJECT_NAME")?.trim() || input.composeProjectName;
  return {
    COMPOSE_PROJECT_NAME: composeProjectName,
    OSVA_IMAGE: imageRef,
    POSTGRES_PASSWORD: postgresPassword,
    OSVA_AUTH_SECRET: authSecret,
    OSVA_PUBLISH_WEB_PORT: String(input.webPort),
    OSVA_PUBLISH_MCP_PORT: String(input.mcpPort),
    OSVA_PUBLISH_CONSOLE_PORT: String(input.consolePort),
    OSVA_AUTH_BASE_URL:
      existing?.get("OSVA_AUTH_BASE_URL")?.trim() || webOrigin,
    OSVA_AUTH_TRUSTED_ORIGINS: mergeInstallTrustedOrigins(
      existing?.get("OSVA_AUTH_TRUSTED_ORIGINS"),
      webOrigin,
      consoleOrigin,
    ),
    OSVA_VALKEY_URL:
      existing?.get("OSVA_VALKEY_URL")?.trim() || "redis://valkey:6379",
  };
}

function mergeInstallTrustedOrigins(
  existing: string | undefined,
  webOrigin: string,
  consoleOrigin: string,
): string {
  const required = [webOrigin, consoleOrigin];
  const merged = new Set<string>();
  for (const origin of required) {
    merged.add(origin);
  }
  const raw = existing?.trim();
  if (raw !== undefined && raw.length > 0) {
    for (const segment of raw.split(",")) {
      const origin = segment.trim();
      if (origin.length > 0) {
        merged.add(origin);
      }
    }
  }
  return [...merged].join(",");
}

function assertRequiredSecret(name: string, value: string): void {
  if (value.length < 32) {
    throw new Error(`${name} must be at least 32 characters for installation.`);
  }
}
