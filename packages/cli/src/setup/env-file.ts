import { readFile } from "node:fs/promises";

import {
  REMOTE_HTTP_DEV_PROFILE_ENV,
  runtimeCapabilityBaseUrlForPort,
} from "./remote-http-dev.js";

/** Required keys for every CLI-managed Compose installation. */
export const CORE_INSTALL_ENV_KEYS = [
  "COMPOSE_PROJECT_NAME",
  "OSVA_IMAGE",
  "POSTGRES_PASSWORD",
  "OSVA_AUTH_SECRET",
  "OSVA_PUBLISH_WEB_PORT",
  "OSVA_PUBLISH_MCP_PORT",
  "OSVA_PUBLISH_CONSOLE_PORT",
  "OSVA_AUTH_BASE_URL",
  "OSVA_AUTH_TRUSTED_ORIGINS",
  "OSVA_VALKEY_URL",
] as const;

export const REMOTE_HTTP_DEV_ENV_KEYS = [
  "OSVA_RUNTIME_CAPABILITY_SECRET",
  "OSVA_RUNTIME_CAPABILITY_PORT",
  "OSVA_PUBLISH_RUNTIME_CAPABILITY_PORT",
  "OSVA_RUNTIME_CAPABILITY_BASE_URL",
  REMOTE_HTTP_DEV_PROFILE_ENV,
] as const;

/** Keys written to the installation `.env` and checked for host-shell conflicts. */
export const INSTALL_ENV_KEYS = [
  ...CORE_INSTALL_ENV_KEYS,
  ...REMOTE_HTTP_DEV_ENV_KEYS,
] as const;

export type InstallEnvKey = (typeof INSTALL_ENV_KEYS)[number];

export type InstallEnvValues = Record<InstallEnvKey, string>;

export interface EnvConflict {
  readonly key: InstallEnvKey;
  readonly shellValue: string;
  readonly fileValue: string;
}

export function parseDotEnv(contents: string): Map<string, string> {
  const values = new Map<string, string>();
  for (const line of contents.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (trimmed.length === 0 || trimmed.startsWith("#")) {
      continue;
    }
    const withoutExport = trimmed.startsWith("export ")
      ? trimmed.slice("export ".length).trim()
      : trimmed;
    const eq = withoutExport.indexOf("=");
    if (eq <= 0) {
      continue;
    }
    const key = withoutExport.slice(0, eq).trim();
    let value = withoutExport.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values.set(key, value);
  }
  return values;
}

export async function readInstallEnvFile(
  envPath: string,
): Promise<Map<string, string> | undefined> {
  try {
    const contents = await readFile(envPath, "utf8");
    return parseDotEnv(contents);
  } catch (error) {
    if (
      error instanceof Error &&
      "code" in error &&
      (error as NodeJS.ErrnoException).code === "ENOENT"
    ) {
      return undefined;
    }
    throw error;
  }
}

export function detectShellEnvConflicts(
  fileValues: InstallEnvValues,
  shellEnv: NodeJS.ProcessEnv,
): readonly EnvConflict[] {
  const conflicts: EnvConflict[] = [];
  const keysToCheck = installEnvConflictKeys(fileValues);
  for (const key of keysToCheck) {
    const shellRaw =
      key === "COMPOSE_PROJECT_NAME"
        ? shellEnv.COMPOSE_PROJECT_NAME?.trim()
        : shellEnv[key]?.trim();
    if (shellRaw === undefined || shellRaw.length === 0) {
      continue;
    }
    const fileValue = fileValues[key];
    if (fileValue.length === 0) {
      continue;
    }
    if (shellRaw !== fileValue) {
      conflicts.push({ key, shellValue: shellRaw, fileValue });
    }
  }
  return conflicts;
}

export function installEnvValuesFromEnvMap(
  envMap: Map<string, string>,
): InstallEnvValues {
  const missing: InstallEnvKey[] = [];
  const core = {} as Pick<
    InstallEnvValues,
    (typeof CORE_INSTALL_ENV_KEYS)[number]
  >;
  for (const key of CORE_INSTALL_ENV_KEYS) {
    const raw = envMap.get(key)?.trim();
    if (raw === undefined || raw.length === 0) {
      missing.push(key);
      continue;
    }
    core[key] = raw;
  }
  if (missing.length > 0) {
    throw new Error(
      `Installation .env is missing required keys: ${missing.join(", ")}.`,
    );
  }
  const remoteHttpDevProfile =
    envMap.get(REMOTE_HTTP_DEV_PROFILE_ENV)?.trim() === "true";
  return {
    ...core,
    OSVA_RUNTIME_CAPABILITY_SECRET:
      envMap.get("OSVA_RUNTIME_CAPABILITY_SECRET")?.trim() ?? "",
    OSVA_RUNTIME_CAPABILITY_PORT:
      envMap.get("OSVA_RUNTIME_CAPABILITY_PORT")?.trim() ?? "",
    OSVA_PUBLISH_RUNTIME_CAPABILITY_PORT:
      envMap.get("OSVA_PUBLISH_RUNTIME_CAPABILITY_PORT")?.trim() ?? "",
    OSVA_RUNTIME_CAPABILITY_BASE_URL:
      envMap.get("OSVA_RUNTIME_CAPABILITY_BASE_URL")?.trim() ?? "",
    [REMOTE_HTTP_DEV_PROFILE_ENV]: remoteHttpDevProfile ? "true" : "false",
  };
}

function installEnvConflictKeys(
  fileValues: InstallEnvValues,
): readonly InstallEnvKey[] {
  if (fileValues[REMOTE_HTTP_DEV_PROFILE_ENV] === "true") {
    return INSTALL_ENV_KEYS;
  }
  return CORE_INSTALL_ENV_KEYS;
}

export function renderInstallEnvFile(values: InstallEnvValues): string {
  const remoteHttpDevLines = renderRemoteHttpDevEnvLines(values);
  const lines = [
    "# Generated by `osva setup`. Do not commit this file.",
    "# Host shell exports override these values during `docker compose` interpolation.",
    "",
    `COMPOSE_PROJECT_NAME=${values.COMPOSE_PROJECT_NAME}`,
    "",
    `OSVA_IMAGE=${values.OSVA_IMAGE}`,
    `POSTGRES_PASSWORD=${values.POSTGRES_PASSWORD}`,
    "",
    "OSVA_VALKEY_URL=redis://valkey:6379",
    "",
    `OSVA_PUBLISH_WEB_PORT=${values.OSVA_PUBLISH_WEB_PORT}`,
    `OSVA_PUBLISH_MCP_PORT=${values.OSVA_PUBLISH_MCP_PORT}`,
    `OSVA_PUBLISH_CONSOLE_PORT=${values.OSVA_PUBLISH_CONSOLE_PORT}`,
    "",
    `OSVA_AUTH_SECRET=${values.OSVA_AUTH_SECRET}`,
    `OSVA_AUTH_BASE_URL=${values.OSVA_AUTH_BASE_URL}`,
    `OSVA_AUTH_TRUSTED_ORIGINS=${values.OSVA_AUTH_TRUSTED_ORIGINS}`,
    "",
    "OSVA_KNOWLEDGE_EMBEDDING_PROVIDER=DETERMINISTIC",
    "OSVA_KNOWLEDGE_EMBEDDING_MODEL=deterministic-v1",
    "OSVA_KNOWLEDGE_EMBEDDING_DIMENSIONS=384",
    "",
    ...remoteHttpDevLines,
  ];
  return `${lines.join("\n")}\n`;
}

function renderRemoteHttpDevEnvLines(values: InstallEnvValues): string[] {
  if (values[REMOTE_HTTP_DEV_PROFILE_ENV] !== "true") {
    return [
      "# Optional: host-based REMOTE_HTTP agent development (`osva setup --remote-http-dev`).",
      `# ${REMOTE_HTTP_DEV_PROFILE_ENV}=true`,
      "",
    ];
  }
  return [
    "# Remote HTTP local development profile (opt-in; not for production).",
    `${REMOTE_HTTP_DEV_PROFILE_ENV}=true`,
    `OSVA_RUNTIME_CAPABILITY_SECRET=${values.OSVA_RUNTIME_CAPABILITY_SECRET}`,
    `OSVA_RUNTIME_CAPABILITY_PORT=${values.OSVA_RUNTIME_CAPABILITY_PORT}`,
    `OSVA_PUBLISH_RUNTIME_CAPABILITY_PORT=${values.OSVA_PUBLISH_RUNTIME_CAPABILITY_PORT}`,
    `OSVA_RUNTIME_CAPABILITY_BASE_URL=${values.OSVA_RUNTIME_CAPABILITY_BASE_URL}`,
    "OSVA_REMOTE_HTTP_ALLOW_PRIVATE_NETWORKS=true",
    "OSVA_MCP_CONNECTOR_ALLOW_PRIVATE_NETWORKS=true",
    "# Model provider credentials (worker-only; set before `docker compose up` worker):",
    "# OPENAI_API_KEY=",
    "# ANTHROPIC_API_KEY=",
    "# GOOGLE_GEMINI_API_KEY=",
    "",
  ];
}

export function buildInstallEnvValues(input: {
  readonly imageRef: string;
  readonly composeProjectName: string;
  readonly webPort: number;
  readonly mcpPort: number;
  readonly consolePort: number;
  readonly runtimeCapabilityPort: number;
  readonly remoteHttpDevProfile: boolean;
  readonly existing?: Map<string, string>;
  readonly generateSecret: () => string;
  /** When true, rewrite auth URLs and trusted origins from the chosen publish ports. */
  readonly refreshPublishedOrigins?: boolean;
}): InstallEnvValues {
  const webOrigin = `http://127.0.0.1:${String(input.webPort)}`;
  const consoleOrigin = `http://127.0.0.1:${String(input.consolePort)}`;
  const refreshOrigins = input.refreshPublishedOrigins === true;
  const existing = input.existing;
  const postgresPassword =
    existing?.get("POSTGRES_PASSWORD")?.trim() || input.generateSecret();
  const authSecret =
    existing?.get("OSVA_AUTH_SECRET")?.trim() || input.generateSecret();
  const imageRef = existing?.get("OSVA_IMAGE")?.trim() || input.imageRef;
  assertRequiredSecret("POSTGRES_PASSWORD", postgresPassword);
  assertRequiredSecret("OSVA_AUTH_SECRET", authSecret);
  const composeProjectName =
    existing?.get("COMPOSE_PROJECT_NAME")?.trim() || input.composeProjectName;
  const remoteHttpDevProfile =
    input.remoteHttpDevProfile ||
    existing?.get(REMOTE_HTTP_DEV_PROFILE_ENV)?.trim() === "true";
  const capabilityPort = readExistingCapabilityPort(
    existing,
    input.runtimeCapabilityPort,
  );
  const capabilitySecret =
    existing?.get("OSVA_RUNTIME_CAPABILITY_SECRET")?.trim() ||
    (remoteHttpDevProfile ? input.generateSecret() : "");
  const capabilityBaseUrl =
    existing?.get("OSVA_RUNTIME_CAPABILITY_BASE_URL")?.trim() ||
    runtimeCapabilityBaseUrlForPort(capabilityPort);

  if (remoteHttpDevProfile) {
    assertRequiredSecret("OSVA_RUNTIME_CAPABILITY_SECRET", capabilitySecret);
  }

  return {
    COMPOSE_PROJECT_NAME: composeProjectName,
    OSVA_IMAGE: imageRef,
    POSTGRES_PASSWORD: postgresPassword,
    OSVA_AUTH_SECRET: authSecret,
    OSVA_PUBLISH_WEB_PORT: String(input.webPort),
    OSVA_PUBLISH_MCP_PORT: String(input.mcpPort),
    OSVA_PUBLISH_CONSOLE_PORT: String(input.consolePort),
    OSVA_AUTH_BASE_URL: refreshOrigins
      ? webOrigin
      : existing?.get("OSVA_AUTH_BASE_URL")?.trim() || webOrigin,
    OSVA_AUTH_TRUSTED_ORIGINS: refreshOrigins
      ? mergeInstallTrustedOrigins(undefined, webOrigin, consoleOrigin)
      : mergeInstallTrustedOrigins(
          existing?.get("OSVA_AUTH_TRUSTED_ORIGINS"),
          webOrigin,
          consoleOrigin,
        ),
    OSVA_VALKEY_URL:
      existing?.get("OSVA_VALKEY_URL")?.trim() || "redis://valkey:6379",
    OSVA_RUNTIME_CAPABILITY_SECRET: remoteHttpDevProfile
      ? capabilitySecret
      : "",
    OSVA_RUNTIME_CAPABILITY_PORT: remoteHttpDevProfile
      ? String(capabilityPort)
      : "",
    OSVA_PUBLISH_RUNTIME_CAPABILITY_PORT: remoteHttpDevProfile
      ? String(capabilityPort)
      : "",
    OSVA_RUNTIME_CAPABILITY_BASE_URL: remoteHttpDevProfile
      ? capabilityBaseUrl
      : "",
    [REMOTE_HTTP_DEV_PROFILE_ENV]: remoteHttpDevProfile ? "true" : "false",
  };
}

function readExistingCapabilityPort(
  existing: Map<string, string> | undefined,
  fallback: number,
): number {
  const raw =
    existing?.get("OSVA_RUNTIME_CAPABILITY_PORT")?.trim() ??
    existing?.get("OSVA_PUBLISH_RUNTIME_CAPABILITY_PORT")?.trim();
  if (raw === undefined || raw.length === 0) {
    return fallback;
  }
  const parsed = Number.parseInt(raw, 10);
  if (!Number.isInteger(parsed) || parsed < 1 || parsed > 65_535) {
    return fallback;
  }
  return parsed;
}

function mergeInstallTrustedOrigins(
  existing: string | undefined,
  webOrigin: string,
  consoleOrigin: string,
): string {
  const required = [webOrigin, consoleOrigin];
  const merged = new Set<string>();
  for (const origin of required) {
    merged.add(origin);
  }
  const raw = existing?.trim();
  if (raw !== undefined && raw.length > 0) {
    for (const segment of raw.split(",")) {
      const origin = segment.trim();
      if (origin.length > 0) {
        merged.add(origin);
      }
    }
  }
  return [...merged].join(",");
}

function assertRequiredSecret(name: string, value: string): void {
  if (value.length < 32) {
    throw new Error(`${name} must be at least 32 characters for installation.`);
  }
}
