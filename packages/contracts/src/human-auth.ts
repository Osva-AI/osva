import type { HumanWorkspacePermission } from "./human-identity.js";
import { HUMAN_WORKSPACE_PERMISSIONS } from "./human-identity.js";

export const HUMAN_AUTH_ROUTE_IDS = {
  LOGIN: "login",
  LOGOUT: "logout",
  SESSION: "session",
  SETUP: "setup",
  RECOVERY_REQUEST: "recovery_request",
  RECOVERY_RESET: "recovery_reset",
  ME: "me",
  WORKSPACES_LIST: "workspaces_list",
  WORKSPACE_SELECT: "workspace_select",
  WORKSPACE_MEMBERSHIPS_LIST: "workspace_memberships_list",
  WORKSPACE_MEMBERSHIP_CREATE: "workspace_membership_create",
  WORKSPACE_MEMBERSHIP_UPDATE: "workspace_membership_update",
  WORKSPACE_MEMBERSHIP_DELETE: "workspace_membership_delete",
  WORKSPACE_OWNERSHIP_TRANSFER: "workspace_ownership_transfer",
  WORKSPACE_OWNERSHIP_GRANT: "workspace_ownership_grant",
  WORKSPACE_MEMBER_PROVISION: "workspace_member_provision",
  AUDIT_EVENTS_LIST: "audit_events_list",
} as const;

export type HumanAuthRouteId =
  (typeof HUMAN_AUTH_ROUTE_IDS)[keyof typeof HUMAN_AUTH_ROUTE_IDS];

export const HUMAN_ROUTE_PERMISSIONS: Readonly<
  Record<HumanAuthRouteId, HumanWorkspacePermission | null>
> = {
  [HUMAN_AUTH_ROUTE_IDS.LOGIN]: null,
  [HUMAN_AUTH_ROUTE_IDS.LOGOUT]: null,
  [HUMAN_AUTH_ROUTE_IDS.SESSION]: null,
  [HUMAN_AUTH_ROUTE_IDS.SETUP]: null,
  [HUMAN_AUTH_ROUTE_IDS.RECOVERY_REQUEST]: null,
  [HUMAN_AUTH_ROUTE_IDS.RECOVERY_RESET]: null,
  [HUMAN_AUTH_ROUTE_IDS.ME]: null,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACES_LIST]: null,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACE_SELECT]: null,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACE_MEMBERSHIPS_LIST]:
    HUMAN_WORKSPACE_PERMISSIONS.MANAGE_MEMBERS,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACE_MEMBERSHIP_CREATE]:
    HUMAN_WORKSPACE_PERMISSIONS.MANAGE_MEMBERS,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACE_MEMBERSHIP_UPDATE]:
    HUMAN_WORKSPACE_PERMISSIONS.MANAGE_MEMBERS,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACE_MEMBERSHIP_DELETE]:
    HUMAN_WORKSPACE_PERMISSIONS.MANAGE_MEMBERS,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACE_OWNERSHIP_TRANSFER]:
    HUMAN_WORKSPACE_PERMISSIONS.TRANSFER_OWNERSHIP,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACE_OWNERSHIP_GRANT]:
    HUMAN_WORKSPACE_PERMISSIONS.TRANSFER_OWNERSHIP,
  [HUMAN_AUTH_ROUTE_IDS.WORKSPACE_MEMBER_PROVISION]:
    HUMAN_WORKSPACE_PERMISSIONS.MANAGE_MEMBERS,
  [HUMAN_AUTH_ROUTE_IDS.AUDIT_EVENTS_LIST]: HUMAN_WORKSPACE_PERMISSIONS.READ,
};

export function humanAuthRouteRequiresWorkspace(
  routeId: HumanAuthRouteId,
): boolean {
  switch (routeId) {
    case HUMAN_AUTH_ROUTE_IDS.LOGIN:
    case HUMAN_AUTH_ROUTE_IDS.LOGOUT:
    case HUMAN_AUTH_ROUTE_IDS.SESSION:
    case HUMAN_AUTH_ROUTE_IDS.SETUP:
    case HUMAN_AUTH_ROUTE_IDS.RECOVERY_REQUEST:
    case HUMAN_AUTH_ROUTE_IDS.RECOVERY_RESET:
    case HUMAN_AUTH_ROUTE_IDS.ME:
    case HUMAN_AUTH_ROUTE_IDS.WORKSPACES_LIST:
    case HUMAN_AUTH_ROUTE_IDS.WORKSPACE_SELECT:
      return false;
    default:
      return true;
  }
}
