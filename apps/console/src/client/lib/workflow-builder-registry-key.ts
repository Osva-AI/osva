/** Registry-safe workflow key slug derived from a display name (create flow only). */
export function slugWorkflowKeyFromName(name: string): string {
  const slug = name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64);
  return slug.length > 0 ? slug : "new-workflow";
}
